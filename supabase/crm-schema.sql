-- ---------------------------------------------------------------------------
create table if not exists crm_buyers (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  company text not null,
  contact_name text,
  designation text,
  email text,
  phone text,
  country text,
  products text,
  hs_codes text,
  status text not null default 'prospect' check (status in ('prospect','engaged','matched','inactive')),
  verified boolean not null default false,
  verification_notes text,
  notes text
);

create table if not exists crm_meetings (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  lead_id uuid references crm_leads(id) on delete set null,
  buyer_id uuid references crm_buyers(id) on delete set null,
  meeting_at timestamptz,
  mode text not null default 'online' check (mode in ('online','in_person','event','intro_email')),
  location text,
  status text not null default 'proposed' check (status in ('proposed','scheduled','completed','no_show','cancelled')),
  outcome text not null default 'pending' check (outcome in ('pending','interested','samples_requested','quotation_sent','order_placed','not_interested')),
  notes text
);

create table if not exists crm_tasks (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  title text not null,
  due_date date,
  priority text not null default 'normal' check (priority in ('low','normal','high')),
  done boolean not null default false,
  completed_at timestamptz,
  lead_id uuid references crm_leads(id) on delete cascade,
  buyer_id uuid references crm_buyers(id) on delete set null,
  assigned_to uuid references crm_users(id) on delete set null,
  notes text
);
create index if not exists crm_tasks_open_idx on crm_tasks(done, due_date);

