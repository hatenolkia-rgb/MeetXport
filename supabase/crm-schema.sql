-- ---------------------------------------------------------------------------
-- Triggers and row level security
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['crm_leads','crm_buyers','crm_meetings','crm_tasks'] loop
    execute format('drop trigger if exists %I_touch on %I', t, t);
    execute format('create trigger %I_touch before update on %I for each row execute function crm_touch_updated_at()', t, t);
  end loop;

  foreach t in array array['crm_leads','crm_activities','crm_buyers','crm_meetings','crm_tasks'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "team full access" on %I', t);
    execute format('drop policy if exists "team read" on %I', t);
    execute format('drop policy if exists "team insert" on %I', t);
    execute format('drop policy if exists "team update" on %I', t);
    execute format('drop policy if exists "super admin delete" on %I', t);
    execute format('create policy "team read" on %I for select to authenticated using (is_crm_user())', t);
    execute format('create policy "team insert" on %I for insert to authenticated with check (is_crm_user())', t);
    execute format('create policy "team update" on %I for update to authenticated using (is_crm_user()) with check (is_crm_user())', t);
    execute format('create policy "super admin delete" on %I for delete to authenticated using (is_crm_super_admin())', t);
  end loop;
end $$;

drop trigger if exists crm_leads_stage_log on crm_leads;
create trigger crm_leads_stage_log after update of stage on crm_leads
  for each row execute function crm_log_stage_change();

-- Team members can delete their own notes; super admins any.
drop policy if exists "own note delete" on crm_activities;
create policy "own note delete" on crm_activities for delete to authenticated
  using (is_crm_user() and user_id = auth.uid() and kind in ('note','call'));

alter table crm_users enable row level security;
drop policy if exists "team reads team" on crm_users;
create policy "team reads team" on crm_users for select to authenticated using (is_crm_user());
drop policy if exists "super admin manages team" on crm_users;
create policy "super admin manages team" on crm_users for update to authenticated
  using (is_crm_super_admin()) with check (is_crm_super_admin());

alter table crm_settings enable row level security;
drop policy if exists "team reads settings" on crm_settings;
create policy "team reads settings" on crm_settings for select to authenticated using (is_crm_user());
drop policy if exists "super admin edits settings" on crm_settings;
create policy "super admin edits settings" on crm_settings for all to authenticated
  using (is_crm_super_admin()) with check (is_crm_super_admin());

alter table crm_dm_sessions enable row level security;
alter table crm_webhook_seen enable row level security;

-- Live updates: new Instagram/website leads pop up in the open CRM without reloading.
do $$
begin
  alter publication supabase_realtime add table crm_leads;
exception when duplicate_object then null;
end $$;

