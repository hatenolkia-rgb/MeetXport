-- Meetxport CRM schema
-- Run once in Supabase: Dashboard → SQL Editor → New query → paste → Run.
-- Safe to re-run: objects are created only if missing, policies are replaced.
--
-- Access model
--   * Only people in crm_users (active) can read or change CRM data.
--   * role 'super_admin' — everything, including team, settings and deleting records.
--   * role 'member'      — day-to-day CRM work (leads, notes, buyers, meetings, tasks).
--   * The website, Instagram/Facebook webhooks and WhatsApp/email sending run on the
--     server (Vercel /api) with the service-role key and never go through these policies.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Team
-- ---------------------------------------------------------------------------
create table if not exists crm_users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text not null,
  role text not null default 'member' check (role in ('super_admin','member')),
  phone text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function is_crm_user() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from crm_users where id = auth.uid() and active);
$$;

create or replace function is_crm_super_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from crm_users where id = auth.uid() and active and role = 'super_admin');
$$;

create or replace function crm_touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Leads — every enquiry from Instagram/Facebook forms, DMs, the website or by hand.
-- lead_no is the permanent serial number, shown as MX-1001, MX-1002, …
-- ---------------------------------------------------------------------------
create table if not exists crm_leads (
  id uuid primary key default gen_random_uuid(),
  lead_no bigint generated by default as identity (start with 1001) unique,
  lead_code text generated always as ('MX-' || lead_no::text) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  source text not null default 'manual' check (source in (
    'instagram_form','facebook_form','instagram_dm','facebook_dm','instagram_comment','facebook_comment',
    'website_form','website_chat','whatsapp','manual','referral','event','other')),
  stage text not null default 'new' check (stage in (
    'new','contacted','follow_up','demo','payment_link','onboarded','lost')),
  assigned_to uuid references crm_users(id) on delete set null,

  -- who they are
  name text,
  company text,
  business_type text check (business_type in ('importer','exporter','importer_exporter','service_provider','beginner','other')),
  experience text check (experience in ('starting','under_1','1_3','3_5','5_plus')),
  city text,
  country text,
  phone text,          -- WhatsApp number, digits with country code (e.g. 919812345678)
  email text,
  products text,
  services text[] not null default '{}',
  message text,

  -- follow-up and sale
  next_follow_up date,
  plan text,
  deal_value numeric(12,2),
  currency text not null default 'INR',
  payment_link text,
  paid_amount numeric(12,2),
  paid_at date,
  renewal_date date,
  lost_reason text,
  notes text,

  -- where it came from
  meta_lead_id text unique,
  meta_form_name text,
  campaign_name text,
  ad_name text,
  social_user_id text,     -- Instagram-scoped / Page-scoped user id of the person who messaged
  social_username text,
  welcome_whatsapp_at timestamptz,
  welcome_email_at timestamptz,
  community_link_at timestamptz
);

create index if not exists crm_leads_stage_idx on crm_leads(stage, created_at desc);
create index if not exists crm_leads_phone_idx on crm_leads(right(phone, 10));
create index if not exists crm_leads_email_idx on crm_leads(lower(email));
create index if not exists crm_leads_social_idx on crm_leads(social_user_id);
create index if not exists crm_leads_follow_idx on crm_leads(next_follow_up);

-- Timeline on each lead: notes, calls, stage changes, WhatsApp/email sent, bot answers.
create table if not exists crm_activities (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  lead_id uuid not null references crm_leads(id) on delete cascade,
  user_id uuid references crm_users(id) on delete set null,  -- null = system / bot
  kind text not null check (kind in ('note','call','stage','whatsapp','email','system','bot')),
  body text not null,
  status text,           -- for whatsapp/email: sent, delivered, read, failed
  external_id text       -- WhatsApp message id / email id, to attach delivery updates
);
create index if not exists crm_activities_lead_idx on crm_activities(lead_id, created_at desc);
create index if not exists crm_activities_ext_idx on crm_activities(external_id);

-- Every stage change is written to the timeline automatically, with who made it.
create or replace function crm_log_stage_change() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.stage is distinct from old.stage then
    insert into crm_activities(lead_id, user_id, kind, body)
    values (new.id, auth.uid(), 'stage', old.stage || ' → ' || new.stage);
  end if;
  return new;
end;
$$;

